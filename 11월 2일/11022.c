#include <stdio.h>

int main() {
    //배열이름은 배열의 첫 번째 주소만을 가리킬 수 있는 포인터 상수다.
    //배열이름은 포인터 상수
    //포인터는 포인터 변수
    int a[5] = { 10, 20, 30, 40, 50 };
    int* p;
    p = a;
    printf("1. %p\n", a); //첫 번째 변수의 주소
    printf("2. %d\n", *p); //10
    printf("3. %d\n", *(p + 1)); //20
    printf("4. %d\n", p[2]); //30
    printf("5. %d\n\n", *(a + 2)); //30
    p = p + 2; //ok
    //a = a + 2; //error : 배열이름은 포인터 상수이기 때문에 변경이 불가능하다.
    //p = a + 2; //ok
    //a = p + 2; //error : 배열이름은 포인터 상수이기 때문에 변경이 불가능하다.
    printf("6. %p\n", a); //첫 번째 변수의 주소
    printf("7. %d\n", *p); //30
    printf("8. %d\n", *(p + 2)); //50
    printf("9. %p\n", p - 1); //두 번째 변수의 주소
    printf("10. %d\n", a[2]); //30
    printf("11. %d\n", p[2]); //50
    printf("12. %d\n", p[-1]); //20
    printf("13. %d\n", *p + 2); //30 + 2 = 32
    return 0;
}